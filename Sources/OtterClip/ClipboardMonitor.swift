import AppKit
import ClipCore
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

private struct NormalizedClipboardImage: Sendable {
    let data: Data
    let width: Int
    let height: Int
}

@MainActor
final class ClipboardMonitor {
    // Retain the original marker to recognize clipboard writes across app versions.
    static let internalType = NSPasteboard.PasteboardType("app.clipshelf.internal")
    private let pasteboard: NSPasteboard
    private let repository: HistoryRepository
    private let preferences: PreferencesStore
    private let sourceProvider: () -> NSRunningApplication?
    private let synchronousImages: Bool
    private let imageQueue = DispatchQueue(label: "app.clipshelf.image-processing", qos: .utility)
    private var captureGeneration: UInt64 = 0
    private var queuedImages = 0
    private var timer: Timer?
    private var changeCount: Int
    var onChange: (() -> Void)?
    var onIssue: ((String) -> Void)?

    init(repository: HistoryRepository, preferences: PreferencesStore, pasteboard: NSPasteboard = .general,
         sourceProvider: @escaping () -> NSRunningApplication? = { NSWorkspace.shared.frontmostApplication },
         synchronousImages: Bool = false) {
        self.repository = repository
        self.preferences = preferences
        self.pasteboard = pasteboard
        self.sourceProvider = sourceProvider
        self.synchronousImages = synchronousImages
        changeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        // Begin with the next copy, leaving the clipboard present at launch untouched.
        changeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    func stop() { timer?.invalidate(); timer = nil; captureGeneration &+= 1 }
    func ignoreCurrentChange() { changeCount = pasteboard.changeCount; captureGeneration &+= 1 }

    func poll() {
        let count = pasteboard.changeCount
        guard count != changeCount else { return }
        changeCount = count
        guard !preferences.value.isPaused else { return }
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            onIssue?("剪贴板访问被系统关闭，请在系统设置中允许 OtterClip 访问剪贴板。")
            return
        }
        let source = sourceProvider()
        guard source?.processIdentifier != ProcessInfo.processInfo.processIdentifier,
              !preferences.value.excludes(source?.bundleIdentifier) else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        let ignored: Set<String> = [
            Self.internalType.rawValue,
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
        ]
        guard types.isDisjoint(with: ignored) else { return }
        // Snapshot content and the foreground application; discard a mid-read clipboard change.
        let appName = source?.localizedName ?? "未知应用"
        let bundleID = source?.bundleIdentifier
        do {
            var item: ClipboardItem?
            if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
                // Files must not fall through to their textual URL representation when disabled.
                guard preferences.value.captureFiles else { return }
                let urls = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
                guard !urls.isEmpty, urls.count <= 1000 else { return }
                let paths = urls.map(\.path)
                item = makeItem(kind: .files, text: "", filePaths: paths, source: appName, bundleID: bundleID,
                                fingerprint: digest(Data(paths.joined(separator: "\u{0}").utf8), kind: .files))
            } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
                guard preferences.value.captureImages else { return }
                guard let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= 20 * 1024 * 1024,
                      pasteboard.changeCount == count else { return }
                let copiedAt = Date()
                if synchronousImages {
                    if let image = Self.normalizeImage(data) { try insertImage(image, source: appName, bundleID: bundleID, copiedAt: copiedAt) }
                } else {
                    guard queuedImages < 3 else { onIssue?("图片处理繁忙，本次图片已跳过。请稍后重新复制。"); return }
                    queuedImages += 1
                    let generation = captureGeneration
                    imageQueue.async { [weak self] in
                        let result = Self.normalizeImage(data)
                        Task { @MainActor [weak self] in
                            guard let self else { return }
                            self.queuedImages -= 1
                            guard generation == self.captureGeneration, !self.preferences.value.isPaused,
                                  self.preferences.value.captureImages, !self.preferences.value.excludes(bundleID), let result else { return }
                            do { try self.insertImage(result, source: appName, bundleID: bundleID, copiedAt: copiedAt) }
                            catch { self.onIssue?("记录图片失败：\(error.localizedDescription)") }
                        }
                    }
                }
                return
            } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                      text.utf8.count <= 2 * 1024 * 1024 {
                item = makeItem(kind: .text, text: text, source: appName, bundleID: bundleID,
                                fingerprint: digest(Data(text.utf8), kind: .text))
            }
            guard let item, pasteboard.changeCount == count else { return }
            repository.insert(item)
            if let error = repository.lastError { onIssue?("历史保存失败：\(error.localizedDescription)") }
            onChange?()
        } catch { onIssue?("记录失败：\(error.localizedDescription)") }
    }

    private nonisolated static func normalizeImage(_ data: Data) -> NormalizedClipboardImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? NSNumber,
              let height = properties[kCGImagePropertyPixelHeight] as? NSNumber,
              width.intValue > 0, height.intValue > 0, width.doubleValue * height.doubleValue <= 40_000_000,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), output.length <= 12 * 1024 * 1024 else { return nil }
        return NormalizedClipboardImage(data: output as Data, width: width.intValue, height: height.intValue)
    }

    private func insertImage(_ image: NormalizedClipboardImage, source: String, bundleID: String?, copiedAt: Date) throws {
        let filename = try repository.storeImage(image.data)
        var item = makeItem(kind: .image, text: "\(image.width) × \(image.height)", imageFile: filename,
                            source: source, bundleID: bundleID, fingerprint: digest(image.data, kind: .image))
        item.createdAt = copiedAt
        item.lastCopiedAt = copiedAt
        repository.insert(item)
        if let error = repository.lastError { onIssue?("历史保存失败：\(error.localizedDescription)") }
        onChange?()
    }

    static func makeItem(kind: ClipKind, text: String, imageFile: String? = nil, filePaths: [String] = [],
                         source: String, bundleID: String? = nil, fingerprint: String) -> ClipboardItem {
        ClipboardItem(id: UUID(), kind: kind, text: text, imageFile: imageFile, filePaths: filePaths,
                      sourceApp: source, sourceBundleID: bundleID, createdAt: Date(), lastCopiedAt: Date(),
                      copyCount: 1, isPinned: false, fingerprint: fingerprint)
    }

    private func makeItem(kind: ClipKind, text: String, imageFile: String? = nil, filePaths: [String] = [],
                          source: String, bundleID: String?, fingerprint: String) -> ClipboardItem {
        Self.makeItem(kind: kind, text: text, imageFile: imageFile, filePaths: filePaths, source: source, bundleID: bundleID, fingerprint: fingerprint)
    }

    static func digest(_ data: Data, kind: ClipKind) -> String {
        kind.rawValue + ":" + SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func digest(_ data: Data, kind: ClipKind) -> String { Self.digest(data, kind: kind) }
}
